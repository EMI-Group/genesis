      → the list, anything undecodable → `[]`. Never raises.

  Unlike the other `tasks` columns, `nil` is handed to the Codec in BOTH
  directions (`nil_as: :delegate`) because its stored form is the `"[]"` TEXT,
  never a NULL column. The remaining `Ecto.Type` glue — the `is_list/1` guard
  and the non-raising `:error` arms — is generated by
  `EvoGit.Store.Types.JsonColumn`.

  Pure module — no Repo, no GenServer, no I/O.
  """

  alias EvoGit.Store.Codec
  alias EvoGit.Store.Types.JsonColumn

  use JsonColumn,
    shape: :strict,
    cast_guard: is_list(value),
    encoder: {Codec, :encode_logs},
    decoder: {Codec, :decode_logs},
    nil_as: :delegate
end

